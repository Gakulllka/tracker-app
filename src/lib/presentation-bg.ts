/**
 * Оформление презентации.
 *
 * Раньше здесь жили шесть «стилей» — Тёмный, Весна, Океан, Ночь, Огонь,
 * Минимал, — из которых пять были идентичны до символа: одинаковый фон,
 * цвета и карточки, различались только название и значок в списке.
 * Остаток от удалённого выбора темы: пресеты свели к монохрому,
 * а список забыли. Честных вариантов ровно два — светлый и тёмный.
 *
 * Вместе с ними удалены одиннадцать настроек фона: эмодзи (количество,
 * размер, прозрачность, скорость, режим анимации) и паттерны (сетка,
 * диагональ, ромбы, волны, зигзаг). Все были выключены по умолчанию и по
 * канону «строго, тихо, надёжно» включаться не должны — но код был живой,
 * и однажды кто-нибудь включил бы падающие ракеты в отчёте руководителю.
 */

export type PresStyleId = "dark" | "light";

export interface PresBgSettings {
  /** Светлый или тёмный слайд. Других вариантов нет. */
  styleId: PresStyleId;
}

export const PRES_STYLES: { id: PresStyleId; label: string }[] = [
  { id: "dark", label: "Тёмная" },
  { id: "light", label: "Светлая" },
];

export const DEFAULT_PRES_BG: PresBgSettings = {
  styleId: "dark",
};
