/**
 * Оформление презентации.
 *
 * Настроек здесь больше нет — и это осознанно.
 *
 * Было шесть «стилей» (Тёмный, Весна, Океан, Ночь, Огонь, Минимал),
 * из которых пять совпадали до символа: одинаковый фон, цвета и карточки,
 * различались только название и значок в списке. Плюс одиннадцать
 * настроек фона: эмодзи с количеством, размером, прозрачностью, скоростью
 * и режимом анимации, и паттерны — сетка, диагональ, ромбы, волны, зигзаг.
 * Ни пресеты, ни выбор стиля нигде не вызывались: сто строк мёртвого кода.
 *
 * Светлая или тёмная — следует теме приложения. Отдельный переключатель
 * означал бы, что слайды могут разойтись с интерфейсом, из которого они
 * сделаны.
 */

/** Тип оставлен ради совместимости хранилища: поле есть, значений нет. */
export interface PresBgSettings {
  /** Зарезервировано. Оформление презентации следует теме приложения. */
  reserved?: never;
}

export const DEFAULT_PRES_BG: PresBgSettings = {};
